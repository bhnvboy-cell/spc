function t(key, params) {
  let s = (I18N[window.SPC_LANG] && I18N[window.SPC_LANG][key]);
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  if (params) {
    Object.keys(params).forEach(k => {
      s = s.split('{' + k + '}').join(params[k]);
    });
  }
  return s;
}

function tStat(label) {
  const key = 'stats.' + label;
  const lang = window.SPC_LANG || 'en';
  if (I18N[lang] && I18N[lang][key] !== undefined) return I18N[lang][key];
  if (I18N.en[key] !== undefined) return I18N.en[key];
  return label;
}
